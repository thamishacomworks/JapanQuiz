function t(key, vars) {
  const table = STRINGS[uiLang] || STRINGS.en;
  let text = table[key] ?? STRINGS.en[key] ?? key;

  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }

  return text;
}

function quizLabel(type) {
  if (!type || !type.includes("-")) return "";

  const [exam, kind] = type.split("-");

  return `${exam.toUpperCase()} · ${t(
    kind === "kanji" ? "kanjiQuiz" : "hiraganaQuiz"
  )}`;
}

function displayAnswer(value) {
  return value === TIME_EXPIRED ? t("timeExpired") : value;
}

function weekdayLabel(date) {
  if (uiLang === "si") {
    return ["ඉරි", "සඳු", "අඟ", "බදා", "බ්‍රහ", "සිකු", "සෙන"][
      date.getDay()
    ];
  }

  return date.toLocaleDateString("en", { weekday: "short" });
}

function applyStaticTexts() {
  document.documentElement.lang = uiLang === "si" ? "si" : "en";

  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }

  for (const el of document.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  }

  for (const button of document.querySelectorAll(".lang-button")) {
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.lang === uiLang)
    );
  }
}

function setUiLanguage(lang) {
  if (lang !== "en" && lang !== "si") return;

  uiLang = lang;

  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // The choice still applies for this visit.
  }

  applyStaticTexts();
  document.dispatchEvent(new CustomEvent("japanquiz-lang"));
}

for (const button of document.querySelectorAll(".lang-button")) {
  button.addEventListener("click", () => {
    setUiLanguage(button.dataset.lang);
  });
}

