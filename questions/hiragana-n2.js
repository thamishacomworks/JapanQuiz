function shuffleN2Hiragana(items) {
  const result = [...items];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

window.HIRAGANA_N2_LEVELS = n2HiraganaGroups.map(
  (group, index) => ({
    id: index + 1,
    title: group.title,

    questions: group.words.map(([word, answer]) => {
      // Use other topics for wrong answers.
      const otherMeanings = [
        ...new Set(
          n2HiraganaGroups
            .filter((_, groupIndex) => groupIndex !== index)
            .flatMap((otherGroup) =>
              otherGroup.words.map((item) => item[1])
            )
            .filter((meaning) => meaning !== answer)
        )
      ];

      const wrongAnswers = shuffleN2Hiragana(
        otherMeanings
      ).slice(0, 3);

      return {
        word,
        answer,
        choices: shuffleN2Hiragana([
          answer,
          ...wrongAnswers
        ])
      };
    })
  })
);