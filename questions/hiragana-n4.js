function shuffleN4Hiragana(items) {
  const result = [...items];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

// Build 10 levels, each containing 10 questions.
window.HIRAGANA_N4_LEVELS = n4HiraganaGroups.map(
  (group, index) => ({
    id: index + 1,
    title: group.title,

    questions: group.words.map(([word, answer]) => {
      const otherMeanings = [
        ...new Set(
          group.words
            .map((item) => item[1])
            .filter((meaning) => meaning !== answer)
        )
      ];

      const wrongAnswers = shuffleN4Hiragana(
        otherMeanings
      ).slice(0, 3);

      return {
        word,
        answer,
        choices: shuffleN4Hiragana([
          answer,
          ...wrongAnswers
        ])
      };
    })
  })
);