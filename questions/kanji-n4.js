function shuffleN4KanjiWords(items) {
  const result = [...items];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

// Create 10 levels with 10 questions each.
window.KANJI_N4_LEVELS = n4KanjiWordGroups.map(
  (group, index) => ({
    id: index + 1,
    title: group.title,

    questions: group.words.map(
      ([word, answer, meaning]) => {
        const otherReadings = [
          ...new Set(
            group.words
              .map((item) => item[1])
              .filter((reading) => reading !== answer)
          )
        ];

        const wrongAnswers = shuffleN4KanjiWords(
          otherReadings
        ).slice(0, 3);

        return {
          word,
          answer,
          meaning,
          choices: shuffleN4KanjiWords([
            answer,
            ...wrongAnswers
          ])
        };
      }
    )
  })
);