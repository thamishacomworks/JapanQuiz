function shuffleN3Hiragana(items) {
  const result = [...items];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

window.HIRAGANA_N3_LEVELS = n3HiraganaGroups.map(
  (group, index) => ({
    id: index + 1,
    title: group.title,

    questions: group.words.map(([word, answer]) => {
      // Use other topics for distractors to avoid
      // closely related meanings within the same topic.
      const otherMeanings = [
        ...new Set(
          n3HiraganaGroups
            .filter((_, groupIndex) => groupIndex !== index)
            .flatMap((otherGroup) =>
              otherGroup.words.map((item) => item[1])
            )
            .filter((meaning) => meaning !== answer)
        )
      ];

      const wrongAnswers = shuffleN3Hiragana(
        otherMeanings
      ).slice(0, 3);

      return {
        word,
        answer,
        choices: shuffleN3Hiragana([
          answer,
          ...wrongAnswers
        ])
      };
    })
  })
);