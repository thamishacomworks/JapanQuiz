// Shuffle a copy of an array.
function shuffleN5KanjiWords(items) {
  const result = [...items];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

// Build 10 levels with 10 questions each.
window.KANJI_N5_LEVELS = n5KanjiWordGroups.map(
  (group, index) => ({
    id: index + 1,
    title: group.title,

    questions: group.words.map(
      ([word, answer, meaning]) => {
        // Use readings from other words in this group
        // as the three wrong answers.
        const otherReadings = [
          ...new Set(
            group.words
              .map((item) => item[1])
              .filter((reading) => reading !== answer)
          )
        ];

        const wrongAnswers = shuffleN5KanjiWords(
          otherReadings
        ).slice(0, 3);

        return {
          word,
          answer,
          meaning,
          choices: shuffleN5KanjiWords([
            answer,
            ...wrongAnswers
          ])
        };
      }
    )
  })
);